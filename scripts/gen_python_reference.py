# --------------------------------------------------------------------------- helpers

_CODE_SPAN = re.compile(r"(``?[^`]+``?)")


def kebab(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "-", name)
    s = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "-", s)
    return s.replace("_", "-").lower()


def escape_prose(text: str) -> str:
    """Escape MDX-significant characters outside inline code; turn RST ``x`` into `x`."""
    out = []
    for part in _CODE_SPAN.split(text):
        if part.startswith("`"):
            inner = part.strip("`")
            out.append(f"`{inner}`")
        else:
            part = (
                part.replace("{", "&#123;")
                .replace("}", "&#125;")
                .replace("<", "&lt;")
                .replace(">", "&gt;")
            )
            out.append(part)
    return "".join(out)


def escape_attr(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', "&quot;").replace("{", "&#123;").replace("}", "&#125;")


def yaml_str(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def first_sentence(text: str) -> str:
    text = " ".join(text.strip().split())
    text = text.replace("``", "`")
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    return (m.group(1) if m else text).strip()


def render_text_block(text: str) -> str:
    """Render docstring prose, keeping fenced code blocks and bullet lists."""
    lines = text.strip("\n").splitlines()
    out: list[str] = []
    in_fence = False
    for line in lines:
        if line.strip().startswith("```"):
            in_fence = not in_fence
            out.append(line.strip() if not in_fence else line.strip())
            continue
        out.append(line if in_fence else escape_prose(line))
    return "\n".join(out).strip()


def ann(a) -> str:
    return "" if a is None else str(a)


def fmt_default(v) -> str | None:
    if v is None:
        return None
    return str(v)


def signature(func, name: str, kind: str = "def") -> str:
    params = []
    for p in func.parameters:
        if p.name in ("self", "cls"):
            continue
        s = p.name
        if p.kind and p.kind.value == "variadic positional":
            s = "*" + s
        elif p.kind and p.kind.value == "variadic keyword":
            s = "**" + s
        if p.annotation is not None:
            s += f": {p.annotation}"
        if p.default is not None:
            s += f" = {p.default}" if p.annotation is not None else f"={p.default}"
        params.append(s)
    prefix = ""
    labels = getattr(func, "labels", set()) or set()
    if "async" in labels:
        prefix = "async "
    decos = ""
    for d in getattr(func, "decorators", []) or []:
        val = str(d.value)
        if "contextmanager" in val or val in ("property", "classmethod", "staticmethod"):
            decos += f"@{val}\n"
    ret = f" -> {func.returns}" if getattr(func, "returns", None) is not None else ""
    head = f"{decos}{prefix}{kind} {name}("
    one = head + ", ".join(params) + ")" + ret
    if len(one.splitlines()[-1]) <= 88 or not params:
        return one
    inner = "".join(f"    {p},\n" for p in params)
    return f"{head}\n{inner})" + ret


def class_signature(cls, name: str) -> str:
    init = cls.members.get("__init__") if hasattr(cls, "members") else None
    if init is not None and getattr(init, "is_function", False):
        sig = signature(init, name, kind="class")
        return re.sub(r" -> None$", "", sig)
    # dataclass / NamedTuple: fields
    fields = [m for m in cls.members.values() if getattr(m, "is_attribute", False) and not m.name.startswith("_")]
    if fields and ("dataclass" in (getattr(cls, "labels", set()) or set()) or any("dataclass" in str(d.value) for d in cls.decorators)):
        params = []
        for f in fields:
            s = f.name
            if f.annotation is not None:
                s += f": {f.annotation}"
            if f.value is not None:
                s += f" = {f.value}"
            params.append(s)
        inner = "".join(f"    {p},\n" for p in params)
        return f"class {name}(\n{inner})"
    bases = ", ".join(str(b) for b in cls.bases)
    return f"class {name}({bases})" if bases else f"class {name}"


# --------------------------------------------------------------------------- docstring rendering


def sections(obj):
    if not obj.docstring:
        return []
    return obj.docstring.parsed


def doc_params(obj) -> dict[str, object]:
    found = {}
    for s in sections(obj):
        if s.kind.value in ("parameters", "other parameters"):
            for p in s.value:
                found[p.name] = p
    return found


def render_params(func, doc_obj=None) -> str:
    """ParamField entries: signature gives types and defaults, the docstring gives descriptions."""
    documented = doc_params(doc_obj or func)
    rows = []
    sig_params = [p for p in func.parameters if p.name not in ("self", "cls")] if func is not None else []
    names = [p.name for p in sig_params] or list(documented)
    sig_by_name = {p.name: p for p in sig_params}
    for n in names:
        sp = sig_by_name.get(n)
        dp = documented.get(n)
        typ = ann(sp.annotation) if sp is not None and sp.annotation is not None else (ann(dp.annotation) if dp else "")
        default = fmt_default(sp.default) if sp is not None else (fmt_default(getattr(dp, "value", None)) if dp else None)
        variadic = sp is not None and sp.kind and sp.kind.value.startswith("variadic")
        required = sp is not None and default is None and not variadic
        desc = render_text_block(dp.description) if dp and dp.description else ""
        attrs = f'body="{escape_attr(n)}"'
        if typ:
            attrs += f' type="{escape_attr(typ)}"'
        if default is not None:
            attrs += f' default="{escape_attr(default)}"'
        if required:
            attrs += " required"
        rows.append(f"<ParamField {attrs}>\n{desc}\n</ParamField>" if desc else f"<ParamField {attrs} />")
    return "\n\n".join(rows)


def _merged(items):
    """Google-style 'Returns:' blocks spanning several lines parse as several items: merge them."""
    merged = []
    for r in items:
        if merged and not r.name and str(r.annotation) == str(merged[-1][0].annotation):
            merged[-1][1].append(r.description or "")
        else:
            merged.append((r, [r.description or ""]))
    out = []
    for r, descs in merged:
        r.description = "\n".join(d for d in descs if d)
        out.append(r)
    return out


def render_returns(obj, kind: str) -> str:
    rows = []
    for s in sections(obj):
        if s.kind.value == kind:
            for r in _merged(s.value):
                typ = ann(r.annotation) or (str(obj.returns) if getattr(obj, "returns", None) is not None else "")
                name = r.name or ("yields" if kind == "yields" else "returns")
                desc = render_text_block(r.description) if r.description else ""
                attrs = f'name="{escape_attr(name)}"'
                attrs += f' type="{escape_attr(typ or "Any")}"'
                rows.append(f"<ResponseField {attrs}>\n{desc}\n</ResponseField>" if desc else f"<ResponseField {attrs} />")
    return "\n\n".join(rows)


def render_attributes(obj) -> str:
    rows = []
    for s in sections(obj):
        if s.kind.value == "attributes":
            for a in s.value:
                typ = ann(a.annotation)
                if not typ and hasattr(obj, "members") and a.name in obj.members and obj.members[a.name].annotation is not None:
                    typ = str(obj.members[a.name].annotation)
                desc = render_text_block(a.description) if a.description else ""
                attrs = f'name="{escape_attr(a.name)}" type="{escape_attr(typ or "Any")}"'
                rows.append(f"<ResponseField {attrs}>\n{desc}\n</ResponseField>" if desc else f"<ResponseField {attrs} />")
    return "\n\n".join(rows)


def render_raises(obj) -> str:
    items = []
    for s in sections(obj):
        if s.kind.value == "raises":
            for r in s.value:
                desc = " ".join(r.description.split()) if r.description else ""
                items.append(f"- `{r.annotation}`: {escape_prose(desc)}" if desc else f"- `{r.annotation}`")
    return "\n".join(items)


def render_examples(obj) -> str:
    blocks = []
    for s in sections(obj):
        if s.kind.value == "examples":
            for kind, text in s.value:
                if kind.value == "examples":
                    blocks.append("```python\n" + text.strip() + "\n```")
                else:
                    t = text.strip()
                    if t.startswith("```"):
                        # normalise fenced block language and indentation
                        body = re.sub(r"^```\w*\n?", "", t)
                        body = re.sub(r"\n?```$", "", body)
                        blocks.append("```python\n" + body.strip("\n") + "\n```")
                    else:
                        blocks.append(render_text_block(t))
    return "\n\n".join(blocks)


_MICRO = re.compile(r"\bmicro[Aa]lgos?\b")


# Sphinx cross-reference roles in docstrings (:class:`~pkg.mod.Name`, :func:`name`) become
# plain inline code; a leading "~" keeps only the last dotted component, as Sphinx renders it.
_ROLE = re.compile(r":(?:func|class|meth|exc|attr|mod|data|obj):`(~?)([^`]+)`")


def _role_to_code(m: re.Match) -> str:
    target = m.group(2).split(".")[-1] if m.group(1) else m.group(2)
    return f"`{target}`"


def normalize_terms(content: str) -> str:
    """Write "microALGO" in prose and turn Sphinx roles into inline code; leave fenced code untouched."""
    out, in_fence = [], False
    for line in content.split("\n"):
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
            out.append(line)
            continue
        if in_fence:
            out.append(line)
            continue
        line = _ROLE.sub(_role_to_code, line)
        parts = re.split(r"(`[^`]*`)", line)
        out.append("".join(p if p.startswith("`") else _MICRO.sub("microALGO", p) for p in parts))
    return "\n".join(out)


def render_admonitions(obj) -> tuple[str, str]:
    """Return (notes, see_also) markdown."""
    notes, see = [], []
    for s in sections(obj):
        if s.kind.value == "admonition":
            title = (s.title or "").lower()
            body = s.value.contents if hasattr(s.value, "contents") else str(s.value)
            if "see also" in title:
                see.append(body)
    see_md = ""
    if see:
        items = []
        for chunk in see:
            for line in chunk.strip().splitlines():
                line = line.strip()
                if not line:
                    continue
                if ":" in line:
                    ref, desc = line.split(":", 1)
                    items.append(f"- `{ref.strip()}`: {escape_prose(desc.strip())}")
                else:
                    items.append(f"- `{line}`")
        see_md = "\n".join(items)
    return "\n\n".join(notes), see_md


def render_text_sections(obj) -> str:
    """Prose and admonitions (except 'See also') in docstring order."""
    texts = []
    for s in sections(obj):
        if s.kind.value == "text":
            texts.append(render_text_block(s.value))
        elif s.kind.value == "admonition":
            title = (s.title or "").strip()
            if "see also" in title.lower():
                continue
            body = s.value.contents if hasattr(s.value, "contents") else str(s.value)
            label = "Notes" if title.lower() in ("note", "notes") else title.rstrip(":")
            texts.append(f"**{escape_prose(label)}**\n\n{render_text_block(body)}")
    return "\n\n".join(texts)


def source_link(obj, pkg: Package) -> str:
    rel = Path(obj.filepath).resolve()
    # path relative to the repository root (parent of the package folder)
    parts = rel.parts
    idx = parts.index(pkg.module)
    rel_path = "/".join(parts[idx:])
    return f"https://github.com/x402-avm/{pkg.repo}/blob/main/{rel_path}#L{obj.lineno}"


def callable_body(func, name: str, pkg: Package, heading_level: str = "##") -> str:
    parts = []
    text = render_text_sections(func)
    if text:
        parts.append(text)
    params = render_params(func)
    if params.strip():
        parts.append(f"{heading_level} Parameters\n\n{params}")
    ret = render_returns(func, "returns")
    if ret:
        parts.append(f"{heading_level} Returns\n\n{ret}")
    yld = render_returns(func, "yields")
    if yld:
        parts.append(f"{heading_level} Yields\n\n{yld}")
    rai = render_raises(func)
    if rai:
        parts.append(f"{heading_level} Raises\n\n{rai}")
    notes, see = render_admonitions(func)
    if notes:
        parts.append(f"{heading_level} Notes\n\n{notes}")
    ex = render_examples(func)
    if ex:
        parts.append(f"{heading_level} Examples\n\n{ex}")
    if see:
        parts.append(f"{heading_level} See also\n\n{see}")
    return "\n\n".join(parts)


def render_method(meth, owner: str) -> str:
    kind = "def"
    name = meth.name
    sig = signature(meth, name, kind)
    body = []
    text = render_text_sections(meth)
    if text:
        body.append(text)
    params = render_params(meth)
    if params.strip():
        body.append(f"**Parameters**\n\n{params}")
    ret = render_returns(meth, "returns")
    if ret:
        body.append(f"**Returns**\n\n{ret}")
    rai = render_raises(meth)
    if rai:
        body.append(f"**Raises**\n\n{rai}")
    notes, _ = render_admonitions(meth)
    if notes:
        body.append(notes)
    ex = render_examples(meth)
    if ex:
        body.append(f"**Example**\n\n{ex}")
    return f"### `{name}`\n\n```python\n{sig}\n```\n\n" + "\n\n".join(body)


def extra_example(pkg: Package, public_name: str) -> str:
    code = EXTRA_EXAMPLES.get(f"{pkg.key}:{public_name}")
    return f"```python\n{code.strip()}\n```" if code else ""


def page_for(obj, public_name: str, import_from: str, pkg: Package) -> tuple[str, str]:
    summary = first_sentence(obj.docstring.value) if obj.docstring else public_name
    kind = "class" if obj.is_class else "function"
    if obj.is_class:
        sig = class_signature(obj, public_name)
    else:
        sig = signature(obj, public_name)
    import_line = (
        f"from {import_from} import {public_name}"
        if obj.name == public_name
        else f"from {import_from} import {public_name}  # defined as {obj.path}"
    )
    lines = [
        "---",
        f"title: {yaml_str(public_name)}",
        f"description: {yaml_str(summary)}",
        "---",
        "",
        GENERATED_NOTE,
        "",
        f"```python Import\n{import_line}\n```",
        "",
        f"```python Signature\n{sig}\n```",
        "",
    ]
    if obj.is_class:
        text = render_text_sections(obj)
        if text:
            lines += [text, ""]
        init = obj.members.get("__init__")
        params = render_params(init if init is not None and init.is_function else None, doc_obj=obj) if (init is not None and init.is_function) else ""
        if not params and doc_params(obj):
            params = render_params(None, doc_obj=obj)
        if params.strip():
            lines += ["## Constructor parameters", "", params, ""]
        attrs = render_attributes(obj)
        if attrs:
            lines += ["## Attributes", "", attrs, ""]
        rai = render_raises(obj)
        if rai:
            lines += ["## Raises", "", rai, ""]
        notes, see = render_admonitions(obj)
        if notes:
            lines += ["## Notes", "", notes, ""]
        ex = render_examples(obj) or extra_example(pkg, public_name)
        if ex:
            lines += ["## Examples", "", ex, ""]
        methods = []
        for m in obj.members.values():
            if getattr(m, "is_alias", False):
                continue
            if not m.is_function or m.name.startswith("_"):
                continue
            methods.append(m)
        props = [
            m for m in obj.members.values()
            if not getattr(m, "is_alias", False) and m.is_function and "property" in (m.labels or set()) and not m.name.startswith("_")
        ]
        if methods:
            lines += ["## Methods", ""]
            for m in methods:
                lines += [render_method(m, public_name), ""]
        if see:
            lines += ["## See also", "", see, ""]
    else:
        lines += [callable_body(obj, public_name, pkg), ""]
        if not render_examples(obj) and extra_example(pkg, public_name):
            lines += ["## Examples", "", extra_example(pkg, public_name), ""]
    lines += [f"<sub>Source: [{source_link(obj, pkg).split('/blob/main/', 1)[1].split('#')[0]}]({source_link(obj, pkg)})</sub>", ""]
    content = "\n".join(lines)
    content = re.sub(r"\n{3,}", "\n\n", content)
    return kind, normalize_terms(content)


def constants_page(loader_pkg, pkg: Package, cp: ConstantsPage) -> str:
    lines = [
        "---",
        f"title: {yaml_str(cp.title)}",
        f"description: {yaml_str(cp.description)}",
        "---",
        "",
        GENERATED_NOTE,
        "",
        f"```python Import\nfrom {cp.import_from} import {', '.join(p.rsplit('.', 1)[1] for p in cp.paths[:4])}\n```",
        "",
    ]
    for path in cp.paths:
        obj = loader_pkg[path.split(".", 1)[1]] if "." in path else loader_pkg
        name = path.rsplit(".", 1)[1]
        value = str(obj.value) if obj.value is not None else ""
        annot = f": {obj.annotation}" if obj.annotation is not None else ""
        doc = render_text_block(obj.docstring.value) if obj.docstring else ""
        lines += [f"## `{name}`", ""]
        if doc:
            lines += [doc, ""]
        m = re.fullmatch(r"\w+\.(\w+)", value)
        if m and m.group(1) in KNOWN_CONSTANTS:
            value = f"{value}  # {KNOWN_CONSTANTS[m.group(1)]}"
        if len(value) > 400:
            lines += [f"```python\n{name}{annot} = ...  # see source\n```", ""]
        else:
            lines += [f"```python\n{name}{annot} = {value}\n```", ""]
        lines += [f"<sub>Source: [{source_link(obj, pkg).split('/blob/main/', 1)[1].split('#')[0]}]({source_link(obj, pkg)})</sub>", ""]
    if pkg.extra_note:
        lines += [pkg.extra_note, ""]
    return re.sub(r"\n{3,}", "\n\n", "\n".join(lines))


def overview_page(pkg: Package, entries: list[tuple[str, list[tuple[str, str, str, str]]]]) -> str:
    lines = [
        "---",
        f"title: {yaml_str(pkg.key + ' reference')}",
        f"sidebarTitle: \"Overview\"",
        f"description: {yaml_str(pkg.summary)}",
        "---",
        "",
        GENERATED_NOTE,
        "",
        f"Every public object of the `{pkg.module}` module ([`{pkg.pypi}` on PyPI](https://pypi.org/project/{pkg.pypi}/)), "
        f"generated from the docstrings in [x402-avm/{pkg.repo}](https://github.com/x402-avm/{pkg.repo}).",
        "",
    ]
    for group, rows in entries:
        lines += [f"## {group}", "", "| Object | Kind | Summary |", "|---|---|---|"]
        for name, kind, slug, summary in rows:
            summary = escape_prose(summary).replace("|", "\\|")
            lines.append(f"| [`{name}`](/reference/python/{pkg.key}/{slug}) | {kind} | {summary} |")
        lines.append("")
    return "\n".join(lines)


def update_docs_json(nav_groups: dict[str, list]) -> None:
    path = SITE / "docs.json"
    data = json.loads(path.read_text())
    replaced = set()

    def walk(node):
        if isinstance(node, dict):
            if node.get("group") in nav_groups and "pages" in node:
                node["pages"] = nav_groups[node["group"]]
                replaced.add(node["group"])
                return
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for v in node:
                walk(v)

    tabs = [t for t in data["navigation"].get("tabs", []) if t.get("tab") == REFERENCE_TAB]
    if not tabs:
        sys.exit(f"docs.json has no navigation tab named {REFERENCE_TAB!r}")
    walk(tabs[0])
    missing = set(nav_groups) - replaced
    if missing:
        sys.exit(f"docs.json has no navigation group named {sorted(missing)}; add an empty one first")
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ai-economy-sdk", default=str(SITE.parent / "ai-economy-sdk"))
    ap.add_argument("--x402-algorand", default=str(SITE.parent / "x402-algorand"))
    args = ap.parse_args()
    roots = {"ai-economy-sdk": Path(args.ai_economy_sdk), "x402-algorand": Path(args.x402_algorand)}

    nav: dict[str, list] = {}
    total = 0
    # Values of x402_algorand constants, used to show what ai_economy_sdk aliases such as
    # ``MAINNET = c.ALGORAND_MAINNET_CAIP2`` resolve to.
    consts = griffe.load(
        "x402_algorand.constants", search_paths=[str(roots["x402-algorand"])],
        allow_inspection=False, resolve_aliases=False,
    )
    for name, member in consts.members.items():
        if not getattr(member, "is_alias", False) and member.is_attribute and member.value is not None and name.isupper():
            KNOWN_CONSTANTS[name] = str(member.value)
    for pkg in PACKAGES:
        root = roots[pkg.key]
        if not (root / pkg.module).is_dir():
            sys.exit(f"{root / pkg.module} not found; pass --{pkg.key} PATH")
        loaded = griffe.load(
            pkg.module,
            search_paths=[str(root)],
            docstring_parser=pkg.docstyle,
            allow_inspection=False,
            resolve_aliases=False,
        )
        out_dir = OUT_ROOT / pkg.key
        if out_dir.exists():
            shutil.rmtree(out_dir)
        out_dir.mkdir(parents=True)
        entries = []
        nav_pages: list = [f"reference/python/{pkg.key}/index"]
        for group in pkg.groups:
            rows = []
            pages = []
            for o in group.objects:
                obj = loaded[o.path.split(".", 1)[1]]
                public = o.name or obj.name
                kind, content = page_for(obj, public, o.import_from or pkg.module, pkg)
                slug = kebab(public)
                (out_dir / f"{slug}.mdx").write_text(content)
                summary = first_sentence(obj.docstring.value) if obj.docstring else ""
                rows.append((public, kind, slug, summary))
                pages.append(f"reference/python/{pkg.key}/{slug}")
                total += 1
            entries.append((group.title, rows))
            nav_pages.append({"group": group.title, "pages": pages})
        if pkg.constants:
            cp = pkg.constants
            (out_dir / f"{cp.slug}.mdx").write_text(normalize_terms(constants_page(loaded, pkg, cp)))
            entries.append(("Constants", [(", ".join(p.rsplit(".", 1)[1] for p in cp.paths[:3]) + ", ...", "constants", cp.slug, cp.description)]))
            nav_pages.append(f"reference/python/{pkg.key}/{cp.slug}")
            total += 1
        (out_dir / "index.mdx").write_text(normalize_terms(overview_page(pkg, entries)))
        nav[pkg.key] = nav_pages
    update_docs_json(nav)
    print(f"wrote {total} object pages and {len(PACKAGES)} overview pages under {OUT_ROOT.relative_to(SITE)}")


if __name__ == "__main__":
    main()
