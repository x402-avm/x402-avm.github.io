#!/usr/bin/env python3
"""Generate the Python API reference (MDX) from the package docstrings.

Reads ``ai_economy_sdk`` (numpy-style docstrings) and ``x402_algorand``
(Google-style docstrings) with griffe's static analysis (nothing is imported or
executed), and writes one MDX page per public object under ``reference/python/``,
an overview page per package, and the matching navigation groups in ``docs.json``.

Usage
-----
    pip install griffe
    python scripts/gen_python_reference.py \
        --ai-economy-sdk ../ai-economy-sdk \
        --x402-algorand ../x402-algorand

Both paths are checkouts of the package repositories (the directory that
contains the ``ai_economy_sdk`` / ``x402_algorand`` package folder). By default
they are the sibling folders ``../ai-economy-sdk`` and ``../x402-algorand``.

The generated pages are committed. Re-run the script whenever a docstring or a
public signature changes, then run ``npx mint@4.3.63 broken-links``.

Objects whose docstring has no Examples section can get one from
``scripts/python_reference_examples.json`` (keyed by ``<package key>:<public name>``).
Prose outside code is normalised to the site's terminology ("microALGO").
"""
