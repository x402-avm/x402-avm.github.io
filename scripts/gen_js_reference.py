#!/usr/bin/env python3
"""Generate the x402-avm-js API reference (MDX) from the TSDoc in src/index.ts.

Every ``export`` in ``src/index.ts`` that carries a ``/** ... */`` TSDoc block becomes one
page under ``reference/js/``. The script also writes ``reference/js/index.mdx`` and
fills the ``x402-avm-js`` group of the "API reference" tab in ``docs.json``.

Interface properties rarely carry their own TSDoc, so their descriptions come from
``scripts/js_reference_overlay.json`` (keyed by ``Interface.property``). A TSDoc comment
on the property itself is used when the overlay has no entry.

Usage
-----
    python scripts/gen_js_reference.py --source ../x402-avm-js/src/index.ts

No dependencies beyond the Python standard library. Re-run whenever the TSDoc or an
exported signature changes, then run ``npx mint@4.3.63 broken-links``.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent
OUT = SITE / "reference" / "js"
OVERLAY = SITE / "scripts" / "js_reference_overlay.json"
REFERENCE_TAB = "API reference"
NAV_GROUP = "x402-avm-js"
SOURCE_URL = "https://github.com/x402-avm/x402-avm-js/blob/main/src/index.ts"
GENERATED_NOTE = (
    "{/* Generated by scripts/gen_js_reference.py from the TSDoc in x402-avm-js/src/index.ts. "
    "Do not edit by hand: edit the TSDoc and re-run the script. */}"
)

CATEGORIES = [
    ("Payments", ["payForRequirement", "decodePaymentRequired", "selectRequirement", "buildExactAvmGroup", "encodePaymentHeader"]),
    ("Identity", ["buildIdentityTxn", "encodeIdentityHeader"]),
    ("Networks", ["resolveNetwork", "networkFromGenesisHash", "networkFromAlgod", "algodClient", "MAINNET", "TESTNET", "LOCALNET_ENDPOINTS"]),
    ("Types", ["PaymentRequired", "PaymentRequirements", "ResourceInfo", "BuildGroupResult", "AlgorandNetwork"]),
]

DECL = re.compile(r"/\*\*((?:(?!\*/)[\s\S])*?)\*/\s*export\s+(interface|const|async\s+function|function)\s+(\w+)")


def kebab(name: str) -> str:
    if name.isupper() or "_" in name:
        return name.lower().replace("_", "-")
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "-", name)
    s = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "-", s)
    return s.lower()


def escape_prose(text: str) -> str:
    out = []
    for part in re.split(r"(`[^`]+`)", text):
        if part.startswith("`"):
            out.append(part)
        else:
            out.append(part.replace("{", "&#123;").replace("}", "&#125;").replace("<", "&lt;").replace(">", "&gt;"))
    return "".join(out)


def escape_attr(text: str) -> str:
    return text.replace('"', "&quot;").replace("{", "&#123;").replace("}", "&#125;")


def match_close(src: str, i: int, open_ch: str, close_ch: str) -> int:
    """Index of the bracket closing the one at src[i]."""
    depth = 0
    for j in range(i, len(src)):
        c = src[j]
        if c == open_ch:
            depth += 1
        elif c == close_ch:
            depth -= 1
            if depth == 0:
                return j
    raise ValueError("unbalanced brackets")


def clean_comment(raw: str) -> str:
    lines = []
    for line in raw.splitlines():
        line = re.sub(r"^\s*\* ?", "", line)
        lines.append(line.rstrip())
    return "\n".join(lines).strip()


def parse_tsdoc(raw: str) -> dict:
    text = clean_comment(raw)
    doc = {"description": "", "params": {}, "returns": "", "throws": [], "examples": []}
    parts = re.split(r"(?m)^(?=@\w+)", text)
    doc["description"] = parts[0].strip()
    for part in parts[1:]:
        m = re.match(r"@(\w+)\s*([\s\S]*)", part)
        tag, body = m.group(1), m.group(2).strip()
        if tag == "param":
            pm = re.match(r"(\w+)\s*-?\s*([\s\S]*)", body)
            doc["params"][pm.group(1)] = " ".join(pm.group(2).split())
        elif tag == "returns":
            doc["returns"] = " ".join(body.split())
        elif tag == "throws":
            tm = re.match(r"\{([^}]*)\}\s*([\s\S]*)", body)
            doc["throws"].append((tm.group(1), " ".join(tm.group(2).split())) if tm else ("Error", " ".join(body.split())))
        elif tag == "example":
            code = re.sub(r"^```\w*\n?", "", body)
            code = re.sub(r"\n?```\s*$", "", code)
            doc["examples"].append(code.rstrip())
    return doc


def split_top(s: str, sep: str) -> list[str]:
    parts, depth, cur = [], 0, ""
    for c in s:
        if c in "({[<":
            depth += 1
        elif c in ")}]>":
            depth -= 1
        if c == sep and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += c
    if cur.strip():
        parts.append(cur)
    return parts


def parse_members(body: str) -> list[dict]:
    """Members of an interface or object type body (text between the outer braces)."""
    members = []
    pending_doc = ""
    i = 0
    chunks = []
    cur = ""
    depth = 0
    while i < len(body):
        if body.startswith("/**", i):
            end = body.index("*/", i)
            if depth == 0:
                pending = clean_comment(body[i + 3:end])
                chunks.append(("doc", pending))
            else:
                cur += body[i:end + 2]
            i = end + 2
            continue
        c = body[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
        if c == ";" and depth == 0:
            chunks.append(("member", cur.strip()))
            cur = ""
        else:
            cur += c
        i += 1
    if cur.strip():
        chunks.append(("member", cur.strip()))
    for kind, val in chunks:
        if kind == "doc":
            pending_doc = val
            continue
        m = re.match(r"(\[[^\]]+\]|\w+)(\?)?\s*:\s*([\s\S]+)", val)
        if not m:
            continue
        name, optional, typ = m.group(1), bool(m.group(2)) or m.group(1).startswith("["), m.group(3).strip()
        member = {"name": name, "optional": optional, "type": typ, "doc": pending_doc, "children": []}
        if typ.startswith("{"):
            member["children"] = parse_members(typ[1:match_close(typ, 0, "{", "}")])
            member["type"] = "object"
        members.append(member)
        pending_doc = ""
    return members


def parse_params(sig_params: str) -> list[dict]:
    out = []
    for p in split_top(sig_params, ","):
        p = " ".join(p.split())
        if not p:
            continue
        m = re.match(r"(\w+)(\?)?\s*:\s*(.+)", p)
        out.append({"name": m.group(1), "optional": bool(m.group(2)), "type": m.group(3).strip()})
    return out


def parse_source(src: str) -> list[dict]:
    decls = []
    for m in DECL.finditer(src):
        raw, kind, name = m.group(1), " ".join(m.group(2).split()), m.group(3)
        start = src.index("export", m.start(2) - 10 if m.start(2) >= 10 else 0)
        start = src.rfind("export", 0, m.end())
        lineno = src.count("\n", 0, start) + 1
        doc = parse_tsdoc(raw)
        d = {"name": name, "kind": kind, "doc": doc, "lineno": lineno}
        if kind == "interface":
            ob = src.index("{", start)
            cb = match_close(src, ob, "{", "}")
            d["decl"] = src[start:cb + 1]
            d["members"] = parse_members(src[ob + 1:cb])
        elif kind == "const":
            ob = src.index("{", start)
            cb = match_close(src, ob, "{", "}")
            end = src.index(";", cb)
            d["decl"] = src[start:end + 1]
            head = src[start:src.index("=", start)].strip()
            d["sig"] = head + ";"
        else:
            op = src.index("(", start)
            cp = match_close(src, op, "(", ")")
            body_open = src.index("{", cp)
            sig = src[start:body_open].rstrip()
            d["sig"] = sig + ";"
            d["params"] = parse_params(src[op + 1:cp])
            ret = src[cp + 1:body_open].strip()
            d["returns_type"] = ret.lstrip(":").strip()
        decls.append(d)
    return decls


def first_sentence(text: str) -> str:
    text = " ".join(text.split())
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    return (m.group(1) if m else text).strip()


def member_fields(iface: str, members: list[dict], overlay: dict, prefix: str = "") -> str:
    rows = []
    for mem in members:
        key = f"{iface}.{prefix}{mem['name']}"
        desc = overlay.get(key) or mem["doc"]
        attrs = f'name="{escape_attr(mem["name"])}" type="{escape_attr(mem["type"])}"'
        if not mem["optional"]:
            attrs += " required"
        inner = escape_prose(desc) if desc else ""
        if mem["children"]:
            child = member_fields(iface, mem["children"], overlay, prefix=f"{prefix}{mem['name']}.")
            inner = (inner + "\n\n" if inner else "") + f'<Expandable title="properties">\n\n{child}\n\n</Expandable>'
        rows.append(f"<ResponseField {attrs}>\n{inner}\n</ResponseField>" if inner else f"<ResponseField {attrs} />")
    return "\n\n".join(rows)


def page(d: dict, overlay: dict) -> str:
    doc = d["doc"]
    summary = first_sentence(doc["description"]) or d["name"]
    is_type = d["kind"] == "interface"
    imp = f"import type {{ {d['name']} }} from 'x402-avm-js';" if is_type else f"import {{ {d['name']} }} from 'x402-avm-js';"
    lines = [
        "---",
        f"title: {json.dumps(d['name'])}",
        f"description: {json.dumps(summary)}",
        "---",
        "",
        GENERATED_NOTE,
        "",
        f"```ts Import\n{imp}\n```",
        "",
    ]
    if is_type:
        lines += [f"```ts Definition\n{d['decl']}\n```", ""]
    elif d["kind"] == "const":
        lines += [f"```ts Definition\n{d['decl']}\n```", ""]
    else:
        lines += [f"```ts Signature\n{d['sig']}\n```", ""]
    if doc["description"]:
        lines += [escape_prose(doc["description"]), ""]
    if is_type:
        lines += ["## Properties", "", member_fields(d["name"], d["members"], overlay), ""]
    if d["kind"] not in ("interface", "const"):
        if d["params"]:
            lines += ["## Parameters", ""]
            for p in d["params"]:
                desc = doc["params"].get(p["name"], "")
                attrs = f'body="{p["name"]}" type="{escape_attr(p["type"])}"'
                if not p["optional"]:
                    attrs += " required"
                lines += [f"<ParamField {attrs}>\n{escape_prose(desc)}\n</ParamField>" if desc else f"<ParamField {attrs} />", ""]
        lines += ["## Returns", "", f'<ResponseField name="returns" type="{escape_attr(d["returns_type"])}">\n{escape_prose(doc["returns"])}\n</ResponseField>', ""]
        if doc["throws"]:
            lines += ["## Throws", ""]
            lines += [f"- `{t}`: {escape_prose(desc)}" for t, desc in doc["throws"]]
            lines += [""]
    if doc["examples"]:
        lines += ["## Example", ""]
        for ex in doc["examples"]:
            lines += [f"```ts\n{ex}\n```", ""]
    lines += [f"<sub>Source: [src/index.ts]({SOURCE_URL}#L{d['lineno']})</sub>", ""]
    return re.sub(r"\n{3,}", "\n\n", "\n".join(lines))


def update_docs_json(pages: list) -> None:
    path = SITE / "docs.json"
    data = json.loads(path.read_text())
    tab = next((t for t in data["navigation"]["tabs"] if t.get("tab") == REFERENCE_TAB), None)
    if tab is None:
        sys.exit(f"docs.json has no tab named {REFERENCE_TAB!r}")
    grp = next((g for g in tab["groups"] if g.get("group") == NAV_GROUP), None)
    if grp is None:
        sys.exit(f"docs.json tab {REFERENCE_TAB!r} has no group named {NAV_GROUP!r}")
    grp["pages"] = pages
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", default=str(SITE.parent / "x402-avm-js" / "src" / "index.ts"))
    args = ap.parse_args()
    src_path = Path(args.source)
    if not src_path.is_file():
        sys.exit(f"{src_path} not found; pass --source PATH/TO/x402-avm-js/src/index.ts")
    src = src_path.read_text()
    overlay = json.loads(OVERLAY.read_text()) if OVERLAY.exists() else {}
    decls = {d["name"]: d for d in parse_source(src)}

    exported = set(re.findall(r"export\s+(?:interface|const|async\s+function|function)\s+(\w+)", src))
    undocumented = exported - set(decls)
    if undocumented:
        sys.exit(f"exports without TSDoc: {sorted(undocumented)}")
    categorised = {n for _, names in CATEGORIES for n in names}
    uncategorised = set(decls) - categorised
    if uncategorised:
        sys.exit(f"add these exports to CATEGORIES in {__file__}: {sorted(uncategorised)}")
    stale = categorised - set(decls)
    if stale:
        sys.exit(f"CATEGORIES lists names that are not exported any more: {sorted(stale)}")

    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    nav: list = ["reference/js/index"]
    index = [
        "---",
        'title: "x402-avm-js reference"',
        'sidebarTitle: "Overview"',
        'description: "Every export of x402-avm-js, generated from the TSDoc in src/index.ts."',
        "---",
        "",
        GENERATED_NOTE,
        "",
        f"`x402-avm-js` has {len(decls)} exports, all named exports of the package root "
        "([`x402-avm-js` on npm](https://www.npmjs.com/package/x402-avm-js)). It is an ES module "
        "with one runtime dependency, `algosdk`.",
        "",
        "```ts",
        "import { payForRequirement, decodePaymentRequired, algodClient } from 'x402-avm-js';",
        "```",
        "",
    ]
    for cat, names in CATEGORIES:
        pages = []
        index += [f"## {cat}", "", "| Export | Kind | Summary |", "|---|---|---|"]
        for n in names:
            d = decls[n]
            slug = kebab(n)
            (OUT / f"{slug}.mdx").write_text(page(d, overlay))
            pages.append(f"reference/js/{slug}")
            kind = {"interface": "interface", "const": "constant"}.get(d["kind"], "function")
            summary = escape_prose(first_sentence(d["doc"]["description"])).replace("|", "\\|")
            index.append(f"| [`{n}`](/reference/js/{slug}) | {kind} | {summary} |")
        index.append("")
        nav.append({"group": cat, "pages": pages})
    (OUT / "index.mdx").write_text("\n".join(index))
    update_docs_json(nav)
    print(f"wrote {len(decls)} export pages and 1 overview page under {OUT.relative_to(SITE)}")


if __name__ == "__main__":
    main()
